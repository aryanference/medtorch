from __future__ import annotations

import copy
import random
from collections.abc import Callable
from collections.abc import Iterable
from collections.abc import Sequence

from torch.utils.data import Dataset

from ..utils import get_subjects_from_batch
from .subject import Subject


class SubjectsDataset(Dataset[Subject]):
    """Base TorchIO dataset.

    Reader of 3D medical images that directly inherits from the PyTorch
    [`Dataset`][torch.utils.data.Dataset]. It can be used with a
    [`SubjectsLoader`][torchio.SubjectsLoader] for efficient loading and
    augmentation. It receives a list of instances of [`Subject`][torchio.Subject]
    and an optional transform applied to the volumes after loading.

    Args:
        subjects: List of instances of [`Subject`][torchio.Subject].
        transform: An instance of [`Transform`][torchio.transforms.Transform]
            that will be applied to each subject.
        load_getitem: Load all subject images before returning it in
            `__getitem__()`. Set it to `False` if some of the images will
            not be needed during training.

    Examples:
        >>> import torchio as tio
        >>> subject_a = tio.Subject(
        ...     t1=tio.ScalarImage('t1.nrrd',),
        ...     t2=tio.ScalarImage('t2.mha',),
        ...     label=tio.LabelMap('t1_seg.nii.gz'),
        ...     age=31,
        ...     name='Fernando Perez',
        ... )
        >>> subject_b = tio.Subject(
        ...     t1=tio.ScalarImage('colin27_t1_tal_lin.minc',),
        ...     t2=tio.ScalarImage('colin27_t2_tal_lin_dicom/',),
        ...     label=tio.LabelMap('colin27_seg1.nii.gz'),
        ...     age=56,
        ...     name='Colin Holmes',
        ... )
        >>> subjects_list = [subject_a, subject_b]
        >>> transforms = [
        ...     tio.RescaleIntensity(out_min_max=(0, 1)),
        ...     tio.RandomAffine(),
        ... ]
        >>> transform = tio.Compose(transforms)
        >>> subjects_dataset = tio.SubjectsDataset(subjects_list, transform=transform)
        >>> subject = subjects_dataset[0]

    !!! tip "Iterating without loading"
        To quickly iterate over the subjects without loading the images,
        use `dry_iter()`.
    """

    def __init__(
        self,
        subjects: Sequence[Subject],
        transform: Callable[[Subject], Subject] | None = None,
        load_getitem: bool = True,
    ):
        self._parse_subjects_list(subjects)
        self._subjects = subjects
        self._transform: Callable[[Subject], Subject] | None
        self.set_transform(transform)
        self.load_getitem = load_getitem

    def __len__(self):
        return len(self._subjects)

    def __getitem__(self, index: int) -> Subject:
        try:
            index = int(index)
        except (RuntimeError, TypeError) as err:
            message = (
                f'Index "{index}" must be int or compatible dtype,'
                f' but an object of type "{type(index)}" was passed'
            )
            raise ValueError(message) from err

        subject = self._subjects[index]
        subject = copy.deepcopy(subject)  # cheap since images not loaded yet
        if self.load_getitem:
            subject.load()

        # Apply transform (this is usually the bottleneck)
        if self._transform is not None:
            subject = self._transform(subject)
        return subject

    @classmethod
    def from_batch(cls, batch: dict) -> SubjectsDataset:
        """Instantiate a dataset from a batch generated by a data loader.

        Args:
            batch: Dictionary generated by a data loader, containing data that
                can be converted to instances of [Subject][.torchio.Subject].
        """
        subjects: list[Subject] = get_subjects_from_batch(batch)
        return cls(subjects)

    def dry_iter(self) -> Sequence[Subject]:
        """Return the internal list of subjects.

        This can be used to iterate over the subjects without loading the data
        and applying any transforms.

        Examples:
            >>> names = [subject.name for subject in dataset.dry_iter()]
        """
        return self._subjects

    def set_transform(
        self,
        transform: Callable[[Subject], Subject] | None,
    ) -> None:
        """Set the `transform` attribute.

        Args:
            transform: Callable object, typically an subclass of
                [`torchio.transforms.Transform`][torchio.transforms.Transform].
        """
        if transform is not None and not callable(transform):
            message = (
                'The transform must be a callable object,'
                f' but it has type {type(transform)}'
            )
            raise ValueError(message)
        self._transform = transform

    def k_fold(
        self,
        k: int = 5,
        seed: int | None = None,
    ) -> list[tuple[SubjectsDataset, SubjectsDataset]]:
        """Split the dataset into *k* stratified cross-validation folds.

        Each fold yields a ``(train_dataset, val_dataset)`` pair where the
        validation set is one contiguous chunk of ``1/k`` of the subjects
        and the training set is the remaining ``(k-1)/k``.

        Args:
            k: Number of folds. Must be at least ``2``.
            seed: Random seed for shuffling subjects before splitting.
                If ``None``, the current random state is used.

        Returns:
            A list of ``k`` tuples ``(train_dataset, val_dataset)``.

        Example:
            >>> for fold_idx, (train_ds, val_ds) in enumerate(dataset.k_fold(k=5)):
            ...     model.fit(train_ds)
            ...     model.evaluate(val_ds)
        """
        if k < 2:
            raise ValueError(f'k must be at least 2, not {k}')
        subjects = list(self._subjects)
        rng = random.Random(seed)
        rng.shuffle(subjects)
        n = len(subjects)
        fold_size = n // k
        folds: list[tuple[SubjectsDataset, SubjectsDataset]] = []
        for i in range(k):
            val_start = i * fold_size
            val_end = val_start + fold_size if i < k - 1 else n
            val_subjects = subjects[val_start:val_end]
            train_subjects = subjects[:val_start] + subjects[val_end:]
            train_ds = SubjectsDataset(
                train_subjects, transform=self._transform
            )
            val_ds = SubjectsDataset(
                val_subjects, transform=self._transform
            )
            folds.append((train_ds, val_ds))
        return folds

    def train_val_split(
        self,
        val_fraction: float = 0.2,
        seed: int | None = None,
    ) -> tuple[SubjectsDataset, SubjectsDataset]:
        """Randomly split into train and validation datasets.

        Args:
            val_fraction: Fraction of subjects reserved for validation.
                Must be in ``(0, 1)``. Default ``0.2``.
            seed: Random seed for reproducibility.

        Returns:
            A ``(train_dataset, val_dataset)`` tuple.

        Example:
            >>> train_ds, val_ds = dataset.train_val_split(val_fraction=0.15, seed=42)
        """
        if not 0 < val_fraction < 1:
            raise ValueError(
                f'val_fraction must be in (0, 1), not {val_fraction}'
            )
        subjects = list(self._subjects)
        rng = random.Random(seed)
        rng.shuffle(subjects)
        n_val = max(1, int(len(subjects) * val_fraction))
        val_subjects = subjects[:n_val]
        train_subjects = subjects[n_val:]
        train_ds = SubjectsDataset(train_subjects, transform=self._transform)
        val_ds = SubjectsDataset(val_subjects, transform=self._transform)
        return train_ds, val_ds

    @staticmethod
    def _parse_subjects_list(subjects_list: Iterable[Subject]) -> None:
        # Check that it's an iterable
        try:
            iter(subjects_list)
        except TypeError as e:
            message = f'Subject list must be an iterable, not {type(subjects_list)}'
            raise TypeError(message) from e

        # Check that it's not empty
        if not subjects_list:
            raise ValueError('Subjects list is empty')

        # Check each element
        for subject in subjects_list:
            if not isinstance(subject, Subject):
                message = (
                    'Subjects list must contain instances of torchio.Subject,'
                    f' not "{type(subject)}"'
                )
                raise TypeError(message)
